/* Sly Weather service worker: maakt de app offline bruikbaar en installeerbaar.
   De pagina zelf: netwerk eerst (zo komt een nieuwe versie meteen door), anders uit de cache.
   Weerdata (Open-Meteo, Buienradar) gaat altijd rechtstreeks naar het netwerk en wordt hier nooit opgeslagen. */
const CACHE = 'sly-weather-v1';
const SHELL = ['./', 'index.html', 'manifest.webmanifest', 'icon-192.png', 'icon-512.png', 'icon-maskable-512.png', 'apple-touch-icon.png'];
self.addEventListener('install', e => { e.waitUntil(caches.open(CACHE).then(c => c.addAll(SHELL)).then(() => self.skipWaiting())); });
self.addEventListener('activate', e => { e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', e => {
  const url = new URL(e.request.url);
  if (url.origin !== location.origin) return; // externe data: niet onderscheppen, niet bewaren
  e.respondWith(fetch(e.request).then(r => { if (r.ok) { const copy = r.clone(); caches.open(CACHE).then(c => c.put(e.request, copy)); } return r; })
    .catch(() => caches.match(e.request).then(r => r || caches.match('./'))));
});
